function h = reasonsAndAppendixHtml(trackAResult, trackBResult, gradeResult, flag, calibConf, reliabilityCategory, overlapResult)
    rowsHtml = '';
    ignoredClasses = {'Background', 'Retina'};
    for i = 1:numel(trackAResult.classNames)
        name = trackAResult.classNames{i};
        if any(strcmp(name, ignoredClasses)), continue; end
        fieldName = matlab.lang.makeValidName(name);
        pixelCount = nnz(trackAResult.masks.(fieldName));
        detected = ternary(pixelCount > 25, 'Yes', 'No');
        detail = ternary(pixelCount > 25, sprintf('%d px region', pixelCount), '-');
        rowsHtml = [rowsHtml sprintf('<tr><td>%s</td><td>%s</td><td>%s</td></tr>', ...
            htmlEscape(name), detected, htmlEscape(detail))]; %#ok<AGROW>
    end
    maDetected = ternary(trackBResult.confirmedCount > 0, 'Yes', ternary(trackBResult.hasAmbiguous, 'Ambiguous', 'No'));
    maDetail = sprintf('%d confirmed, %s ambiguous candidate(s)', trackBResult.confirmedCount, ...
        ternary(trackBResult.hasAmbiguous, 'has', 'no'));
    rowsHtml = [rowsHtml sprintf('<tr><td>Microaneurysms</td><td>%s</td><td>%s</td></tr>', maDetected, htmlEscape(maDetail))];

    noteHtml = '';
    if overlapResult.hasUnexplainedRegion
        noteHtml = '<p class="note-warn">Note: Grad-CAM highlights a region Module 2 did not flag - worth a second look.</p>';
    end

    h = [ ...
        '<div class="section">' sectionHead('5', 'Grading Reasons (Detail)') ...
        sprintf(['<table class="reasons"><thead><tr><th>Finding</th><th>Detected</th><th>Detail</th></tr></thead>' ...
            '<tbody>%s</tbody></table>'], rowsHtml) ...
        '<div class="reasoning-block">' ...
        '<div class="reasoning-label">Rule-based path (Module 2 findings):</div>' ...
        sprintf('<div>%s</div>', htmlEscape(gradeResult.rule.reason)) ...
        sprintf('<div class="reasoning-label">Deep-learning grading model: Grade %d</div>', gradeResult.cnn.grade) ...
        sprintf('<div class="reasoning-label">Final shown grade: %d</div>', gradeResult.shownGrade) ...
        sprintf('<div>%s</div>', htmlEscape(flag.message)) ...
        '</div>' ...
        '<div class="reasoning-block"><div class="reasoning-label">Technical Appendix</div>' ...
        '<div class="infogrid" style="margin-top:8px;">' ...
        infoField('Calibrated Confidence', sprintf('%.0f%% (%s)', calibConf * 100, reliabilityCategory)) ...
        infoField('Lesion-Attention Overlap', sprintf('%.0f%%', overlapResult.overlapScore * 100)) ...
        infoField('CNN Continuous Score', sprintf('%.2f / 4', gradeResult.cnn.continuousScore)) ...
        infoField('CNN Raw Confidence', sprintf('%.2f (uncalibrated)', gradeResult.cnn.rawConfidence)) ...
        '</div>' noteHtml '</div></div>' ...
    ];
end

