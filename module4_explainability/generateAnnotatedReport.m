function reportPath = generateAnnotatedReport(rgbImage, enhImg, qc, trackAResult, trackBResult, ...
    gradeResult, camResult, overlapResult, patientInfo, imageId, reportPath)
%GENERATEANNOTATEDREPORT Module 4: build the final clinical report as a PDF.
%   reportPath = generateAnnotatedReport(rgbImage, enhImg, qc, trackAResult,
%       trackBResult, gradeResult, camResult, overlapResult, patientInfo,
%       imageId, reportPath)
%
%   Renders real HTML/CSS (matching the web app's ReportPage.tsx layout
%   and styling - same section numbering, pill badges, InfoGrid,
%   findings table) and converts it to PDF via headless Microsoft Edge
%   (--print-to-pdf). Earlier versions hand-positioned MATLAB text()/
%   rectangle() calls at manually-tuned normalized coordinates -
%   workable in principle, but every pass at "make it look professional"
%   kept surfacing new spacing/alignment misses, because that approach
%   has no real layout engine behind it. HTML/CSS is what actually
%   produces the reference look (it IS how the web report is rendered),
%   so this generates the same kind of document the same way instead of
%   approximating it by hand.
%
%   Built as small per-section HTML fragments (buildXSectionHtml below),
%   each its own sprintf call with only its own arguments, rather than
%   one giant format string - a single 30+ argument sprintf is exactly
%   the kind of thing that silently misaligns (wrong value in wrong
%   table cell) with no error to catch it.
%
%   Section structure mirrors ReportPage.tsx directly: 1 Recommendation,
%   2 Retinal Findings (image + findings table), 3 DR Severity
%   Assessment, 4 AI Analysis Visualizations (segmentation overlay +
%   Grad-CAM + color legend) - plus a MATLAB-report-only Grading Reasons
%   detail table and Technical Appendix. Per-lesion location/count/
%   reliability come from the shared buildLesionFindings.m so the two
%   report surfaces can't silently disagree.
%
%   patientInfo (all optional - pass [] or omit fields for "Unknown"):
%     .diabetesControl / .diabetesDurationYears / .hba1c / .patientId
%
%   Requires Microsoft Edge installed locally (bundled with Windows).
%
%   See also: gradeImage, computeGradCAM, lesionAttentionOverlap,
%   calibrateConfidence, categorizeReliability, getFollowUpRecommendation,
%   buildLesionFindings, buildLesionOverlay.

    if nargin < 9 || isempty(patientInfo)
        patientInfo = struct();
    end
    if nargin < 10 || isempty(imageId)
        imageId = 'unknown';
    end
    if nargin < 11 || isempty(reportPath)
        reportPath = fullfile('results', sprintf('report_%s.pdf', imageId));
    end

    flag = gradeResult.flag;
    calibConf = calibrateConfidence(gradeResult.cnn.rawConfidence);
    reliabilityCategory = categorizeReliability(calibConf);
    followUp = getFollowUpRecommendation(gradeResult.shownGrade, flag.flagged);
    findings = buildLesionFindings(trackAResult, trackBResult);
    lesionOverlay = buildLesionOverlay(enhImg, trackAResult, trackBResult);

    body = [ ...
        headerAndPatientHtml(imageId, patientInfo), ...
        recommendationSectionHtml(gradeResult, flag, followUp), ...
        findingsSectionHtml(rgbImage, qc, findings), ...
        '<div class="page-break"></div>', ...
        severitySectionHtml(gradeResult, flag), ...
        visualizationsSectionHtml(lesionOverlay, camResult), ...
        '<div class="page-break"></div>', ...
        reasonsAndAppendixHtml(trackAResult, trackBResult, gradeResult, flag, calibConf, reliabilityCategory, overlapResult), ...
        footerHtml() ...
    ];

    html = ['<!DOCTYPE html><html><head><meta charset="utf-8"><style>' reportCss() '</style></head><body>' body '</body></html>'];
    reportPath = renderHtmlToPdf(html, reportPath);
end

% ============================================================
% HTML -> PDF via headless Edge
% ============================================================

function reportPath = renderHtmlToPdf(html, reportPath)
    edgeCandidates = {
        'C:\Program Files (x86)\Microsoft\Edge\Application\msedge.exe'
        'C:\Program Files\Microsoft\Edge\Application\msedge.exe'
    };
    edgeExe = '';
    for i = 1:numel(edgeCandidates)
        if isfile(edgeCandidates{i})
            edgeExe = edgeCandidates{i};
            break
        end
    end
    if isempty(edgeExe)
        error('generateAnnotatedReport:noEdge', ...
            'Microsoft Edge not found at either standard install location - needed to render the HTML report to PDF.');
    end

    outDir = fileparts(reportPath);
    if ~isempty(outDir) && ~isfolder(outDir)
        mkdir(outDir);
    end
    % A fixed, readable filename rather than a random tempname() - Edge's
    % headless print always stamps a timestamp + source URL header/footer
    % on every page (matching the reference report, itself a browser
    % print - --print-to-pdf-no-header does not suppress this on the
    % installed Edge build, tested directly), so what that footer shows
    % actually matters instead of being a throwaway path.
    renderDir = fullfile(outDir, '.report_render');
    if ~isfolder(renderDir)
        mkdir(renderDir);
    end
    htmlPath = fullfile(renderDir, 'report_preview.html');
    fid = fopen(htmlPath, 'w', 'n', 'UTF-8');
    fwrite(fid, html, 'char');
    fclose(fid);

    if isfile(reportPath)
        delete(reportPath);
    end
    cmd = sprintf('"%s" --headless --disable-gpu --no-sandbox --print-to-pdf="%s" --print-to-pdf-no-header "file:///%s"', ...
        edgeExe, reportPath, strrep(htmlPath, '\', '/'));
    [status, cmdOut] = system(cmd);
    delete(htmlPath);
    if status ~= 0 || ~isfile(reportPath)
        error('generateAnnotatedReport:renderFailed', 'Edge headless PDF render failed: %s', cmdOut);
    end
end

function uri = imageToDataUri(img)
%IMAGETODATAURI JPEG-encode an image in memory and return a base64
%data: URI, so the HTML report is one self-contained file with no
%external image references for Edge headless to resolve.
    tmp = [tempname() '.jpg'];
    imwrite(im2uint8(img), tmp, 'Quality', 85);
    fid = fopen(tmp, 'r');
    bytes = fread(fid, Inf, 'uint8=>uint8');
    fclose(fid);
    delete(tmp);
    uri = ['data:image/jpeg;base64,' matlab.net.base64encode(bytes)];
end

