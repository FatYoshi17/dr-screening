function h = headerAndPatientHtml(imageId, patientInfo)
    h = [ ...
        '<div class="brand-row"><div class="brand-left"><div class="brand-mark">DS</div>' ...
        '<div><div class="brand-title">Diabetic Retinopathy Screening Report</div>' ...
        '<div class="brand-sub">AI-Assisted Automated Fundus Analysis</div></div></div>' ...
        sprintf('<div class="meta-right"><b>Image ID:</b> %s<br>Date: %s</div></div>', ...
            htmlEscape(imageId), datestr(now, 'mm/dd/yyyy')) ... %#ok<TNOW1,DATST>
        '<hr class="top">' ...
        '<div class="patient-grid">' ...
        infoField('Patient ID', htmlEscape(valueOrUnknown(patientInfo, 'patientId', '%s'))) ...
        infoField('Diabetes Control', htmlEscape(valueOrUnknown(patientInfo, 'diabetesControl', '%s'))) ...
        infoField('Duration of Diabetes', htmlEscape(valueOrUnknown(patientInfo, 'diabetesDurationYears', '%g years'))) ...
        infoField('HbA1c', htmlEscape(valueOrUnknown(patientInfo, 'hba1c', '%.1f%%'))) ...
        '</div>' ...
    ];
end

function h = infoField(label, value)
    h = sprintf('<div><div class="field-label">%s</div><div class="field-value">%s</div></div>', ...
        htmlEscape(label), value);
end

function h = sectionHead(number, title)
    h = sprintf(['<div class="section-head"><span class="section-num">%s</span>' ...
        '<span class="section-title">%s</span></div><hr class="section-rule">'], number, htmlEscape(title));
end

function h = recommendationSectionHtml(gradeResult, flag, followUp)
    resultCategory = resultCategoryOf(gradeResult);
    [pillClass, planClass] = toneClasses(resultCategory);

    disagreeHtml = '';
    if flag.flagged
        bannerText = ternary(strcmp(flag.priority, 'high'), ...
            'High-risk lesion pattern requires specialist confirmation.', ...
            'Possible false alarm - specialist confirmation recommended.');
        disagreeHtml = sprintf([ ...
            '<div class="disagree-banner"><div class="disagree-title">&#9888; Automated Opinions Disagree</div>' ...
            '<div class="disagree-body">%s</div></div>'], htmlEscape(bannerText));
    end

    h = [ ...
        '<div class="section">' sectionHead('1', 'Recommendation') ...
        sprintf('<span class="pill %s">%s</span>', pillClass, resultCategory) ...
        sprintf(['<div class="plan-box %s"><div class="plan-label">Recommended Clinical Action Plan</div>' ...
            '<div class="plan-text">%s</div></div>'], planClass, htmlEscape(followUp)) ...
        disagreeHtml ...
        '</div>' ...
    ];
end

function h = findingsSectionHtml(rgbImage, qc, findings)
    origUri = imageToDataUri(rgbImage);
    qualityLabel = qualityCategoryLabel(qc.decision);
    qualityClass = ternary(strcmp(char(qc.decision), 'Pass'), 'routine', ...
        ternary(strcmp(char(qc.decision), 'Reject'), 'priority', 'review'));

    rowsHtml = '';
    for i = 1:numel(findings)
        f = findings(i);
        rowsHtml = [rowsHtml sprintf([ ...
            '<tr><td class="lt">%s</td><td>%d</td><td class="loc">%s</td>' ...
            '<td><span class="conf %s">%s</span></td></tr>'], ...
            htmlEscape(f.lesionType), f.count, htmlEscape(f.location), ...
            reliabilityClass(f.reliabilityCategory), f.reliabilityCategory)]; %#ok<AGROW>
    end
    if isempty(findings)
        rowsHtml = '<tr><td colspan="4" class="empty">No lesions detected above the reporting threshold.</td></tr>';
    end

    h = [ ...
        '<div class="section">' sectionHead('2', 'Retinal Findings') ...
        '<div class="findings-row"><div>' ...
        sprintf('<div class="fundus-box"><img src="%s"></div>', origUri) ...
        sprintf('<div class="quality-pill-row"><span class="pill %s">Overall Quality: %s</span></div>', ...
            qualityClass, qualityLabel) ...
        '</div>' ...
        sprintf(['<div style="flex:1;"><table class="findings"><thead><tr>' ...
            '<th>Lesion Type</th><th>Count</th><th>Location</th><th>Confidence</th>' ...
            '</tr></thead><tbody>%s</tbody></table></div>'], rowsHtml) ...
        '</div></div>' ...
    ];
end

function h = severitySectionHtml(gradeResult, flag)
    referableClass = ternary(gradeResult.isReferable, 'danger', 'success');
    agreementClass = ternary(~flag.flagged, 'success', 'warn');
    h = [ ...
        '<div class="section">' sectionHead('3', 'DR Severity Assessment') ...
        '<div class="infogrid">' ...
        infoField('ICDR Severity Grade', sprintf('Grade %d - %s', gradeResult.shownGrade, htmlEscape(gradeLabel(gradeResult.shownGrade)))) ...
        sprintf('<div><div class="field-label">Referable DR</div><div class="field-value val %s">%s</div></div>', ...
            referableClass, ternary(gradeResult.isReferable, 'YES', 'NO')) ...
        infoField('Grading Pathway', ternary(gradeResult.rule.committed, 'Rule-based', 'CNN')) ...
        sprintf('<div><div class="field-label">Rule / CNN Agreement</div><div class="field-value val %s">%s</div></div>', ...
            agreementClass, ternary(~flag.flagged, 'Agree', 'Disagreement - flagged')) ...
        '</div></div>' ...
    ];
end

