% ============================================================
% Small helpers
% ============================================================

function cat = resultCategoryOf(gradeResult)
    if gradeResult.flag.flagged
        cat = ternary(strcmp(gradeResult.flag.priority, 'high'), 'PRIORITY', 'REVIEW');
    elseif gradeResult.shownGrade >= 3
        cat = 'PRIORITY';
    elseif gradeResult.shownGrade == 2
        cat = 'REVIEW';
    else
        cat = 'ROUTINE';
    end
end

function [pillClass, planClass] = toneClasses(resultCategory)
    switch resultCategory
        case 'PRIORITY'
            pillClass = 'priority'; planClass = 'priority';
        case 'REVIEW'
            pillClass = 'review'; planClass = 'review';
        otherwise
            pillClass = 'routine'; planClass = 'routine';
    end
end

function cls = reliabilityClass(category)
    switch category
        case 'Reliable'
            cls = 'reliable';
        case 'Moderate'
            cls = 'moderate';
        otherwise
            cls = 'low';
    end
end

function label = qualityCategoryLabel(decision)
    switch char(decision)
        case 'Pass'
            label = 'PASS';
        case 'Enhance'
            label = 'ACCEPTABLE';
        case 'Reject'
            label = 'REJECT';
        otherwise
            label = upper(char(decision));
    end
end

function label = gradeLabel(grade)
    labels = {'No DR', 'Mild NPDR', 'Moderate NPDR', 'Severe NPDR', 'Proliferative DR'};
    if grade >= 0 && grade <= 4
        label = labels{grade + 1};
    else
        label = 'Unknown';
    end
end

function str = valueOrUnknown(s, fieldName, fmt)
    if isfield(s, fieldName) && ~isempty(s.(fieldName))
        str = sprintf(fmt, s.(fieldName));
    else
        str = 'Unknown';
    end
end

function out = ternary(cond, a, b)
    if cond, out = a; else, out = b; end
end

function esc = htmlEscape(str)
    str = char(str);
    esc = strrep(str, '&', '&amp;');
